#!/usr/bin/env python3
"""Generate config/p3.pal.symbol_addrs.txt from the function map and relocation-derived symbols."""
import json, re
fmap = json.load(open('config/p3.pal.func_map.json'))
symmap = json.load(open('pal_work/symmap.json'))
extra = {}
try:
    for l in open('config/p3.pal.symbol_overrides.txt'):
        m = re.match(r'(\S+)\s*=\s*(0x[0-9a-fA-F]+);(.*)', l)
        if m: extra[m.group(1)] = (int(m.group(2), 16), m.group(3).strip())
except FileNotFoundError:
    pass
# proto data-symbol attributes (size etc.) are not transferable; names only
out = {}
for o in fmap:
    if o['conf'] in ('anchored', 'estimate') and o['est'] is not None and not o['file'].startswith('sce/'):
        out[o['name']] = (o['est'], '// type:func')
for k, v in symmap.items():
    if ':' in k: continue                      # section bases, not symbols
    (a, c), *rest = v.items()
    tot = c + sum(x for _, x in rest)
    if rest and c / tot < 0.8: continue
    a = int(a, 16)
    if k in out or a < 0x100000: continue
    if 0x100000 <= a < 0x185960: out[k] = (a, '// type:func')
    else: out[k] = (a, '')
out.update(extra)
# one name per address: prefer functions from the map
byaddr = {}
for n, (a, c) in sorted(out.items(), key=lambda x: x[1][0]):
    byaddr.setdefault(a, (n, c))
with open('config/p3.pal.symbol_addrs.txt', 'w') as f:
    f.write("// Generated by tools/pal/gen_syms.py -- edit config/p3.pal.symbol_overrides.txt instead.\n")
    for a, (n, c) in sorted(byaddr.items()):
        f.write(f"{n:<60s} = {a:#010x}; {c}\n".rstrip() + "\n")
print(len(byaddr), "symbols")
